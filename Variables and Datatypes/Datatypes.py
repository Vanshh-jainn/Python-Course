# Data Types in Python
# Python supports several built-in data types:

# -Integers (int): Whole numbers (e.g., 10, -5).
# -Floats (float): Decimal numbers (e.g., 3.14, -0.001).
# -strings (str): Text data enclosed in quotes (e.g., "Hello", 'Python').
# -Booleans (bool): Represents True or False.
integer = 1 #int
float_number = 3.4 #float
String = "vansh" #str
Boolean = True or False  #bool 



# -Lists: Ordered, mutable collections (e.g., [1, 2, 3]).
# -Tuples: Ordered, immutable collections (e.g., (1, 2, 3)).
# -Sets: Unordered collections of unique elements (e.g., {1, 2, 3}).
# Dictionaries: Key-value pairs (e.g., {"name": "Alice", "age": 25}).
Lists = [1,2,34,4,5,]
Tuple = (1,2,34)
Sets = {1,2,43,5,6,}
Dictionaries = {"name":"Vansh", "Age":19}

# We can use (type) function to print the type of variable
print(integer)
print(type(integer))